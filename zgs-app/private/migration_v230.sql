CREATE TABLE IF NOT EXISTS mail_folders (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(190) NOT NULL UNIQUE,
 uidvalidity BIGINT UNSIGNED NOT NULL DEFAULT 0, last_uid BIGINT UNSIGNED NOT NULL DEFAULT 0,
 last_sync DATETIME NULL, last_error VARCHAR(190) NOT NULL DEFAULT ''
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mail_messages (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, folder_id INT UNSIGNED NOT NULL,
 uidvalidity BIGINT UNSIGNED NOT NULL, remote_uid BIGINT UNSIGNED NOT NULL,
 message_id VARCHAR(255) NOT NULL DEFAULT '', sender VARCHAR(500) NOT NULL,
 recipients TEXT NOT NULL, subject VARCHAR(500) NOT NULL, sent_at DATETIME NULL,
 body MEDIUMTEXT NOT NULL, seen TINYINT NOT NULL DEFAULT 0, active TINYINT NOT NULL DEFAULT 1,
 important TINYINT NOT NULL DEFAULT 0, answered TINYINT NOT NULL DEFAULT 0,
 automatic_message TINYINT NOT NULL DEFAULT 0,
 property_id INT UNSIGNED NULL, customer_id INT UNSIGNED NULL, task_id INT UNSIGNED NULL,
 invoice_id BIGINT UNSIGNED NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_mail_uid(folder_id,uidvalidity,remote_uid),
 INDEX idx_mail_list(folder_id,active,sent_at),
 FOREIGN KEY(folder_id) REFERENCES mail_folders(id) ON DELETE RESTRICT,
 FOREIGN KEY(property_id) REFERENCES properties(id) ON DELETE RESTRICT,
 FOREIGN KEY(customer_id) REFERENCES customers(id) ON DELETE RESTRICT,
 FOREIGN KEY(task_id) REFERENCES tasks(id) ON DELETE RESTRICT,
 FOREIGN KEY(invoice_id) REFERENCES invoices(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mail_attachments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, message_id BIGINT UNSIGNED NOT NULL,
 original_name VARCHAR(255) NOT NULL, mime_type VARCHAR(100) NOT NULL,
 stored_name CHAR(64) NOT NULL, size_bytes INT UNSIGNED NOT NULL, sha256 CHAR(64) NOT NULL,
 UNIQUE KEY uq_mail_attachment(message_id,sha256,original_name),
 FOREIGN KEY(message_id) REFERENCES mail_messages(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mail_drafts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, to_address TEXT NOT NULL,
 cc_address TEXT NOT NULL, subject VARCHAR(190) NOT NULL, body MEDIUMTEXT NOT NULL,
 reply_message_id BIGINT UNSIGNED NULL, reply_header VARCHAR(255) NOT NULL DEFAULT '',
 message_id VARCHAR(190) NOT NULL UNIQUE,
 status ENUM('draft','sending','accepted','uncertain','rejected','manual_confirmed') NOT NULL DEFAULT 'draft',
 sent_copy TINYINT NOT NULL DEFAULT 0, last_error VARCHAR(190) NOT NULL DEFAULT '',
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(reply_message_id) REFERENCES mail_messages(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS mail_draft_attachments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, draft_id BIGINT UNSIGNED NOT NULL,

 stored_name CHAR(64) NOT NULL, size_bytes INT UNSIGNED NOT NULL, sha256 CHAR(64) NOT NULL,
 UNIQUE KEY uq_draft_attachment(draft_id,sha256,original_name),
 FOREIGN KEY(draft_id) REFERENCES mail_drafts(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
